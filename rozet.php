const AKSANLI = [
    'Ç' => ['C', 'cengel'],
    'Ş' => ['S', 'cengel'],
    'Ğ' => ['G', 'kisa'],
    'İ' => ['I', 'nokta'],
    'Ö' => ['O', 'iki_nokta'],
    'Ü' => ['U', 'iki_nokta']
];

const AKSAN_SATIRLARI = [
    'nokta' => [[1, '.#.']],
    'iki_nokta' => [[1, '.#.#.']],
    'kisa' => [[0, '#...#'], [1, '.###.']],
    'cengel' => [[10, '..#..'], [11, '.##..']],
];

function glif(string $harf): array
{
    if ($harf === ' ') return array_fill(0, 12, '...');
    $aksan = AKSANLI[$harf] ?? null;
    $govde = HARFLER[$aksan ? $aksan[0] : $harf] ?? HARFLER['-'];
    $genislik = strlen($govde[0]);
    $satirlar = array_fill(0, 12, str_repeat('.', $genislik));
    foreach ($govde as $i => $satir) $satirlar[3 + $i] = $satir;
    if ($aksan) foreach (AKSAN_SATIRLARI[$aksan[1]] as [$i, $s]) $satirlar[$i] = substr(str_pad($s, $genislik, '.'), 0, $genislik);
    return $satirlar;
}

function rozet(string $yazi, string $renk): string
{
    $yazi = mb_strtoupper(str_replace(['i', 'ı'], ['İ', 'I'], $yazi), 'UTF-8');
    $harfler = mb_str_split($yazi, 1, 'UTF-8');
    $metinGenisligi = -1;
    foreach ($harfler as $h) $metinGenisligi += strlen(glif($h)[3]) + 1;
    $w = 4 + 3 + 3 + max(0, $metinGenisligi) + 6;
    $h = 13;
    $parca = [];
    $x0 = 10;
    foreach ($harfler as $harf) {
        $satirlar = glif($harf);
        foreach ($satirlar as $y => $satir) {
            for ($x = 0; $x < strlen($satir); $x++) {
                if ($satir[$x] !== '#') continue;
                $son = $x;
                while ($son < strlen($satir) && $satir[$son] === '#') $son++;
                $parca[] = sprintf('<rect x="%d" y="%d" width="%d" height="1"/>', $x0 + $x, $y - 1, $son - $x);
                $x = $son - 1;
            }
        }
        $x0 += strlen($satirlar[3]) + 1;
    }
    $kenar = sprintf('<path fill="#%1$s" d="M1 0h%2$dv1h1v%3$dh-1v1h-%2$dv-1h-1v-%3$dh1z"/>', $renk, $w - 2, $h - 2);
    $ic = sprintf('<rect x="1" y="1" width="%d" height="%d" fill="#140b36"/>', $w - 2, $h - 2);
    $kare = sprintf('<rect x="4" y="5" width="3" height="3" fill="#%s"/>', $renk);
    return sprintf(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %1$d %2$d" width="%3$d" height="%4$d" shape-rendering="crispEdges">%5$s%6$s%7$s<g fill="#f1eaff">%8$s</g></svg>',
        $w, $h, $w * 3, $h * 3, $kenar, $ic, $kare, implode('', $parca)
    );
}

